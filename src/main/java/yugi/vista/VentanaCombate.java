private void actualizarInterfaz() {

    lblLP1.setText(controlador.getJugador1().getPuntosVida() + " LP");
    lblLP2.setText(controlador.getJugador2().getPuntosVida() + " LP");

    txtMonstruos1.setText(controlador.obtenerMonstruosJugador1());
    txtMonstruos2.setText(controlador.obtenerMonstruosJugador2());

    cmbAtacante.removeAllItems();
    cmbDefensor.removeAllItems();

    for (Monstruo monstruo : controlador.getJugador1().getMonstruos()) {
        cmbAtacante.addItem(monstruo.getNombreMonstruo());
    }

    cmbDefensor.addItem("Ataque directo");

    for (Monstruo monstruo : controlador.getJugador2().getMonstruos()) {
        cmbDefensor.addItem(monstruo.getNombreMonstruo());
    }
}
