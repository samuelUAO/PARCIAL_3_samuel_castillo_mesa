    private void btnAtacarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtacarActionPerformed
int atacante = cmbAtacante.getSelectedIndex();
int defensor = cmbDefensor.getSelectedIndex();

if (atacante == -1 || defensor == -1) {
    JOptionPane.showMessageDialog(this,
            "Selecciona los monstruos primero.");
    return;
}

String resultado = controlador.atacar(
        atacante,
        defensor == 0 ? -1 : defensor - 1
);

txtResultado.setText(resultado);
txtResultado.setLineWrap(true);
txtResultado.setWrapStyleWord(true);

actualizarInterfaz();

if (controlador.hayGanador()) {
    JOptionPane.showMessageDialog(this,
            controlador.obtenerGanador());
}
    }//GEN-LAST:event_btnAtacarActionPerformed

